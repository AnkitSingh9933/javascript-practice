/*

Topic: Array indexOf()

What I learned today:
- indexOf() returns the index of an element.
- If element is not found, it returns -1.
- Index starts from 0.
*/

var fruits = ["Apple", "Mango", "Banana", "Orange"];

var mangoIndex = fruits.indexOf("Mango");
console.log("Mango index:", mangoIndex);

var grapeIndex = fruits.indexOf("Grapes");
console.log("Grapes index:", grapeIndex);
